
import { useState, useEffect } from 'react';
import { listActivesProducts } from '../services/productService';
export function useProducts() {
  const [products, setProducts] = useState([]);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState(null);

  const fetchProducts = async () => {
    try {
      setLoading(true);
       const data = await listActivesProducts();
       setProducts(data);
      setError(null);
    } catch (err) {
      setError(err.message);
    } finally {
      setLoading(false);
    }
  };

  useEffect(() => {
    fetchProducts();
  }, []);

  return {
    products,
    loading,
    error,
    refetchProducts: fetchProducts, // Permitirá recargar los datos de prueba
  };
}